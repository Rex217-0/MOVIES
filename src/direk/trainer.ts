/**
 * LoRA auto-trainer for Direk.
 *
 * After a set is generated, Direk can train it without leaving the app. This
 * module prepares a real dataset directory on disk (images + captions), writes
 * the kohya config, and runs the trainer as a child process while streaming its
 * output.
 *
 * It runs locally, so it needs kohya_ss / sd-scripts on this machine. Nothing
 * here fakes a training run: with no trainer installed the job is reported as
 * unavailable.
 *
 * Configuration (environment variables):
 *   TRAIN_BACKEND       `local` (default) runs kohya here; `colab` hands the run
 *                       to a Colab notebook through a Drive folder.
 *   KOHYA_DIR           Path to kohya_ss or sd-scripts (must contain
 *                       train_network.py). Enables training.
 *   KOHYA_PYTHON        Python interpreter, default `python3` (POSIX) or
 *                       `python` on Windows
 *   KOHYA_BASE_MODEL    Base model path or HuggingFace id. Required to train.
 *   KOHYA_ACCELERATE    Set to `1` to launch via `accelerate launch`
 *   KOHYA_OUTPUT_DIR    Where runs are written, default `<cwd>/lora_runs`
 *   KOHYA_TIMEOUT_MS    Hard cap on a run, default 6 hours
 *
 * The two backends sit behind one interface (`TrainBackend`), so the routes do
 * not care which one is live. `local` is the default and is unchanged.
 */

import { spawn, type ChildProcess } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { defaultPython, killSignal } from './platform.ts';

export interface TrainerStatus {
  available: boolean;
  dir: string;
  script: string | null;
  python: string;
  base_model: string | null;
  output_dir: string;
  reason?: string;
}

export interface TrainJob {
  id: string;
  trigger: string;
  title: string;
  status: 'running' | 'done' | 'failed' | 'cancelled';
  startedAt: string;
  finishedAt?: string;
  outputDir: string;
  log: string[];
  artifact?: string;
  error?: string;
}

/** Path to the kohya training script, or null when not installed. */
export function trainerScript(dir: string): string | null {
  for (const rel of ['train_network.py', 'sdxl_train_network.py']) {
    const p = path.join(dir, rel);
    if (fs.existsSync(p)) return p;
  }
  return null;
}

/** Report whether training can run on this machine. */
export function trainerStatus(): TrainerStatus {
  const dir = process.env.KOHYA_DIR || '';
  const python = process.env.KOHYA_PYTHON || defaultPython();
  const baseModel = process.env.KOHYA_BASE_MODEL || null;
  const outputDir = process.env.KOHYA_OUTPUT_DIR || path.join(process.cwd(), 'lora_runs');

  if (!dir) {
    return {
      available: false, dir, script: null, python, base_model: baseModel, output_dir: outputDir,
      reason: 'KOHYA_DIR is not set. Point it at a kohya_ss / sd-scripts checkout to enable training.',
    };
  }
  const script = trainerScript(dir);
  if (!script) {
    return {
      available: false, dir, script: null, python, base_model: baseModel, output_dir: outputDir,
      reason: `No train_network.py or sdxl_train_network.py in ${dir}.`,
    };
  }
  if (!baseModel) {
    return {
      available: false, dir, script, python, base_model: null, output_dir: outputDir,
      reason: 'KOHYA_BASE_MODEL is not set. Training needs a base model.',
    };
  }
  return { available: true, dir, script, python, base_model: baseModel, output_dir: outputDir };
}

/** The command that starts a training run for `configPath`. */
export function buildTrainCommand(
  status: TrainerStatus,
  configPath: string,
): { cmd: string; args: string[] } {
  const script = status.script as string;
  if (process.env.KOHYA_ACCELERATE === '1') {
    return {
      cmd: 'accelerate',
      args: ['launch', '--num_cpu_threads_per_process', '2', script, '--config_file', configPath],
    };
  }
  return { cmd: status.python, args: [script, '--config_file', configPath] };
}

/** Pull step/epoch progress out of a kohya log line, if it is there. */
export function parseProgress(line: string): string | null {
  const steps = line.match(/steps:\s*(\d+)\/(\d+)/i);
  if (steps) return `steps ${steps[1]}/${steps[2]}`;
  const epoch = line.match(/epoch\s+(\d+)\/(\d+)/i);
  if (epoch) return `epoch ${epoch[1]}/${epoch[2]}`;
  return null;
}

/**
 * A kohya config for a real on-disk dataset directory. Unlike the download
 * config, every path here is absolute so the trainer can actually find things.
 */
export function trainingConfig(opts: {
  datasetDir: string;
  outputDir: string;
  outputName: string;
  baseModel: string;
  resolution: number;
  numRepeats: number;
  maxEpochs: number;
  networkDim: number;
  networkAlpha: number;
  seed: number;
}): string {
  return `# kohya_ss LoRA config generated by Direk (MOVIE CREATOR)
# Dataset: ${opts.datasetDir}
# Base model: ${opts.baseModel}

[general]
enable_bucket = true
bucket_no_upscale = false
output_dir = "${opts.outputDir}"
output_name = "${opts.outputName}"
save_model_as = "safetensors"

[[datasets]]
resolution = ${opts.resolution}
batch_size = 1
enable_bucket = true

  [[datasets.subsets]]
  image_dir = "${opts.datasetDir}"
  caption_extension = ".txt"
  num_repeats = ${opts.numRepeats}

[network_arguments]
network_module = "networks.lora"
network_dim = ${opts.networkDim}
network_alpha = ${opts.networkAlpha}

[optimizer_arguments]
learning_rate = 1e-4
optimizer_type = "AdamW8bit"
lr_scheduler = "cosine_with_restarts"
lr_scheduler_num_cycles = 3

[training_arguments]
pretrained_model_name_or_path = "${opts.baseModel}"
max_train_epochs = ${opts.maxEpochs}
save_every_n_epochs = 2
mixed_precision = "fp16"
seed = ${opts.seed}

[logging_arguments]
logging_dir = "${path.join(opts.outputDir, 'logs')}"
log_with = "tensorboard"
`;
}

/** Write the dataset images, captions and config for a run. */
export function writeTrainingJob(opts: {
  root: string;
  trigger: string;
  captions: { name: string; text: string }[];
  images: Map<string, Buffer>;
  config: string;
  /** Called with the trained file path when a run finishes successfully. */
  onArtifact?: (filePath: string) => void;
}): { datasetDir: string; configPath: string; imagesWritten: number } {
  const datasetDir = path.join(opts.root, 'dataset');
  fs.mkdirSync(datasetDir, { recursive: true });

  let imagesWritten = 0;
  for (const { name, text } of opts.captions) {
    fs.writeFileSync(path.join(datasetDir, `${name}.txt`), `${text}\n`, 'utf8');
    const png = opts.images.get(name);
    if (png) {
      fs.writeFileSync(path.join(datasetDir, `${name}.png`), png);
      imagesWritten++;
    }
  }

  const configPath = path.join(opts.root, 'kohya_config.toml');
  fs.writeFileSync(configPath, opts.config, 'utf8');
  return { datasetDir, configPath, imagesWritten };
}

/** Find the newest .safetensors a finished run produced. */
export function findArtifact(outputDir: string): string | undefined {
  try {
    const found = fs
      .readdirSync(outputDir)
      .filter(f => f.endsWith('.safetensors'))
      .map(f => ({ f, t: fs.statSync(path.join(outputDir, f)).mtimeMs }))
      .sort((a, b) => b.t - a.t);
    return found.length ? path.join(outputDir, found[0].f) : undefined;
  } catch {
    return undefined;
  }
}

export interface StartTrainOptions {
  id: string;
  title: string;
  trigger: string;
  root: string;
  captions: { name: string; text: string }[];
  images: Map<string, Buffer>;
  config: string;
  /** Called with the trained file path when a run finishes successfully. */
  onArtifact?: (filePath: string) => void;
}

/** Which trainer runs the job. `local` is the default and is unchanged. */
export type TrainBackendName = 'local' | 'colab';

/** The backend chosen by `TRAIN_BACKEND`, defaulting to `local`. */
export function trainBackendName(): TrainBackendName {
  return process.env.TRAIN_BACKEND === 'colab' ? 'colab' : 'local';
}

/**
 * The one interface both trainers sit behind. The routes call this and never
 * care whether kohya runs here or a Colab notebook runs the job through Drive.
 */
export interface TrainBackend {
  readonly name: TrainBackendName;
  /** Whether training can run at all, with the reason when it cannot. */
  status(): TrainerStatus;
  /** The current or last job, or null when nothing has run yet. */
  current(): TrainJob | null;
  /** Start a run. Rejects when one is going or the backend is unavailable. */
  start(opts: StartTrainOptions): Promise<TrainJob>;
  /** Ask the run to stop. Resolves true when a stop was requested. */
  cancel(): Promise<boolean>;
  /** Follow the run's log lines; returns an unsubscribe function. */
  onLine(fn: (line: string) => void): () => void;
  /** The most recent log lines, oldest first, for an SSE replay. */
  recentLog(max?: number): string[];
}

/** The local kohya_ss / sd-scripts trainer, unchanged, behind the interface. */
export class LocalTrainBackend implements TrainBackend {
  readonly name = 'local' as const;
  private readonly trainer = new LoRATrainer();

  status(): TrainerStatus {
    return trainerStatus();
  }

  current(): TrainJob | null {
    return this.trainer.current();
  }

  async start(opts: StartTrainOptions): Promise<TrainJob> {
    return this.trainer.start(opts);
  }

  async cancel(): Promise<boolean> {
    return this.trainer.cancel();
  }

  onLine(fn: (line: string) => void): () => void {
    return this.trainer.onLine(fn);
  }

  recentLog(max = 100): string[] {
    return (this.trainer.current()?.log ?? []).slice(-max);
  }
}

/**
 * Owns at most one training run at a time and exposes its state. The heavy
 * lifting happens in a child process; this class only starts it, captures its
 * output, and remembers the result.
 */
export class LoRATrainer {
  private job: TrainJob | null = null;
  private child: ChildProcess | null = null;
  private listeners = new Set<(line: string) => void>();

  current(): TrainJob | null {
    return this.job;
  }

  onLine(fn: (line: string) => void): () => void {
    this.listeners.add(fn);
    return () => this.listeners.delete(fn);
  }

  private emit(line: string) {
    for (const fn of this.listeners) {
      try { fn(line); } catch { /* a dead listener must not stop the run */ }
    }
  }

  /** Start a run. Throws when one is already going or the trainer is missing. */
  start(opts: StartTrainOptions): TrainJob {
    if (this.job?.status === 'running') {
      throw new Error('May tumatakbong training na. Hintayin itong matapos o i-cancel.');
    }
    const status = trainerStatus();
    if (!status.available) {
      throw new Error(status.reason || 'Hindi available ang trainer.');
    }

    const outputDir = path.join(status.output_dir, opts.id);
    fs.mkdirSync(outputDir, { recursive: true });
    const written = writeTrainingJob({
      root: opts.root,
      trigger: opts.trigger,
      captions: opts.captions,
      images: opts.images,
      config: opts.config,
    });

    const job: TrainJob = {
      id: opts.id,
      title: opts.title,
      trigger: opts.trigger,
      status: 'running',
      startedAt: new Date().toISOString(),
      outputDir,
      log: [],
    };
    this.job = job;

    const push = (line: string) => {
      const text = line.replace(/\s+$/, '');
      if (!text) return;
      job.log.push(text);
      if (job.log.length > 400) job.log.splice(0, job.log.length - 400);
      this.emit(text);
    };

    push(`dataset: ${written.datasetDir} (${written.imagesWritten} images)`);
    push(`output: ${outputDir}`);

    const { cmd, args } = buildTrainCommand(status, written.configPath);
    push(`$ ${cmd} ${args.map(a => (a.includes(' ') ? `"${a}"` : a)).join(' ')}`);

    const timeoutMs = Number(process.env.KOHYA_TIMEOUT_MS) || 6 * 60 * 60 * 1000;
    let child: ChildProcess;
    try {
      child = spawn(cmd, args, { cwd: status.dir, env: process.env });
    } catch (error: any) {
      job.status = 'failed';
      job.error = error?.message || 'Hindi ma-start ang trainer.';
      push(`error: ${job.error}`);
      return job;
    }
    this.child = child;

    const timer = setTimeout(() => {
      push(`error: lumampas sa timeout (${Math.round(timeoutMs / 60000)} min)`);
      job.status = 'failed';
      job.error = 'Training timed out.';
      child.kill(killSignal());
    }, timeoutMs);

    child.stdout?.on('data', (b: Buffer) => b.toString().split('\n').forEach(push));
    child.stderr?.on('data', (b: Buffer) => b.toString().split('\n').forEach(push));
    child.on('error', (err: Error) => {
      clearTimeout(timer);
      job.status = 'failed';
      job.error = err.message;
      push(`error: ${err.message}`);
    });
    child.on('close', (code: number | null) => {
      clearTimeout(timer);
      this.child = null;
      if (job.status === 'cancelled' || job.status === 'failed') return;
      if (code === 0) {
        job.status = 'done';
        job.artifact = findArtifact(outputDir);
        push(job.artifact ? `tapos: ${job.artifact}` : 'tapos (walang .safetensors na nakita)');
        if (job.artifact && opts.onArtifact) {
          try { opts.onArtifact(job.artifact); } catch (e: any) {
            push(`warning: hindi na-publish ang LoRA: ${e?.message || e}`);
          }
        }
      } else {
        job.status = 'failed';
        job.error = `Trainer exited with code ${code}.`;
        push(`error: ${job.error}`);
      }
      job.finishedAt = new Date().toISOString();
    });

    return job;
  }

  cancel(): boolean {
    if (this.job?.status !== 'running' || !this.child) return false;
    this.job.status = 'cancelled';
    this.job.finishedAt = new Date().toISOString();
    this.emit('cancelled');
    this.child.kill('SIGTERM');
    this.child = null;
    return true;
  }
}
